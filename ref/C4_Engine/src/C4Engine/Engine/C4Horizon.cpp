Texture *HorizonProcess::horizonTexture = nullptr;


HorizonProcess::HorizonProcess() : TextureMapProcess(kProcessHorizon)
{
	horizonFlags = 0;
	
	secondaryTextureName[0] = 0;
	secondaryTextureObject = nullptr;
}

HorizonProcess::HorizonProcess(const HorizonProcess& horizonProcess) : TextureMapProcess(horizonProcess)
{
	horizonFlags = horizonProcess.horizonFlags;
	secondaryTextureName = horizonProcess.secondaryTextureName;
	
	Texture *texture = horizonProcess.secondaryTextureObject;
	if (texture) texture->Retain();
	secondaryTextureObject = texture;
}

HorizonProcess::~HorizonProcess()
{
	if (secondaryTextureObject) secondaryTextureObject->Release();
}

Process *HorizonProcess::Replicate(void) const
{
	return (new HorizonProcess(*this));
}

void HorizonProcess::Initialize(void)
{
	horizonTexture = Texture::Get(&horizonTextureHeader, horizonTextureImage);
}

void HorizonProcess::Terminate(void)
{
	horizonTexture->Release();
}

bool HorizonProcess::ValidShader(ProcessType type, int32 shader)
{
	return (shader == kShaderGraphLight);
}

void HorizonProcess::Pack(Packer& data, unsigned_int32 packFlags) const
{
	TextureMapProcess::Pack(data, packFlags);
	
	data << horizonFlags;
	data << secondaryTextureName;
}

void HorizonProcess::Unpack(Unpacker& data, unsigned_int32 unpackFlags)
{
	TextureMapProcess::Unpack(data, unpackFlags);
	
	data >> horizonFlags;
	
	data >> secondaryTextureName;
	SetSecondaryTexture(secondaryTextureName);
}

void *HorizonProcess::BeginSettingsUnpack(void)
{
	if (secondaryTextureObject)
	{
		secondaryTextureObject->Release();
		secondaryTextureObject = nullptr;
	}
	
	return (TextureMapProcess::BeginSettingsUnpack());
}

int32 HorizonProcess::GetSettingCount(void) const
{
	return (TextureMapProcess::GetSettingCount() + 4);
}

Setting *HorizonProcess::GetSetting(int32 index) const
{
	int32 count = TextureMapProcess::GetSettingCount();
	if (index < count) return (TextureMapProcess::GetSetting(index));
	
	const StringTable *table = TheInterfaceMgr->GetStringTable();
	
	if (index == count)
	{
		const char *title = table->GetString(StringID('PROC', kProcessHorizon, 'TNM2'));
		const char *picker = table->GetString(StringID('PROC', kProcessHorizon, 'PICK'));
		return (new ResourceSetting('TNM2', secondaryTextureName, title, picker, TextureResource::GetDescriptor()));
	}
	
	if (index == count + 1)
	{
		const char *title = table->GetString(StringID('PROC', kProcessHorizon, 'XINF'));
		return (new BooleanSetting('XINF', ((horizonFlags & kHorizonExcludeInfiniteLight) != 0), title));
	}
	
	if (index == count + 2)
	{
		const char *title = table->GetString(StringID('PROC', kProcessHorizon, 'XPNT'));
		return (new BooleanSetting('XPNT', ((horizonFlags & kHorizonExcludePointLight) != 0), title));
	}
	
	if (index == count + 3)
	{
		const char *title = table->GetString(StringID('PROC', kProcessHorizon, 'DETL'));
		return (new BooleanSetting('DETL', ((GetProcessFlags() & kProcessHighDetail) != 0), title));
	}
	
	return (nullptr);
}

void HorizonProcess::SetSetting(const Setting *setting)
{
	Type identifier = setting->GetSettingIdentifier();
	
	if (identifier == 'TNM2')
	{
		SetSecondaryTexture(static_cast<const ResourceSetting *>(setting)->GetResourceName());
	}
	else if (identifier == 'XINF')
	{
		bool b = static_cast<const BooleanSetting *>(setting)->GetBooleanValue();
		if (b) horizonFlags |= kHorizonExcludeInfiniteLight;
		else horizonFlags &= ~kHorizonExcludeInfiniteLight;
	}
	else if (identifier == 'XPNT')
	{
		bool b = static_cast<const BooleanSetting *>(setting)->GetBooleanValue();
		if (b) horizonFlags |= kHorizonExcludePointLight;
		else horizonFlags &= ~kHorizonExcludePointLight;
	}
	else if (identifier == 'DETL')
	{
		unsigned_int32 flags = GetProcessFlags();
		bool b = static_cast<const BooleanSetting *>(setting)->GetBooleanValue();
		if (b) SetProcessFlags(flags | kProcessHighDetail);
		else SetProcessFlags(flags & ~kProcessHighDetail);
	}
	else
	{
		TextureMapProcess::SetSetting(setting);
	}
}

void HorizonProcess::SetSecondaryTexture(const char *name)
{
	Texture *object = secondaryTextureObject;
	
	if (name)
	{
		if (name != &secondaryTextureName[0]) secondaryTextureName = name;
		secondaryTextureObject = Texture::Get(name);
	}
	else
	{
		secondaryTextureName[0] = 0;
		secondaryTextureObject = nullptr;
	}
	
	if (object) object->Release();
}

