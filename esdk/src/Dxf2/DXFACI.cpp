inline int ABS(int a, int b)
{
	if (a > b) return (a - b);
	return (b - a);
}

ACI::ACI(int nACI, int nRed, int nGreen, int nBlue)
{
	m_nACI = nACI;
	m_nRed = nRed;
	m_nGreen = nGreen;
	m_nBlue = nBlue;
}

ACI::~ACI(void)
{
}

bool ACI::ACIToRGB(int nACI, int* pRed, int* pGreen, int* pBlue)
{
	if (nACI <= 0 || nACI > 255) return false;

	*pRed = ACITable[nACI-1].m_nRed;
	*pGreen = ACITable[nACI-1].m_nGreen;
	*pBlue = ACITable[nACI-1].m_nBlue;
	return true;
}

bool ACI::RGBToACI(int nRed, int nGreen, int nBlue, int* pACI)
{
	if (nRed < 0 || nRed > 255) return false;
	if (nGreen < 0 || nGreen > 255) return false;
	if (nBlue < 0 || nBlue > 255) return false;

	int nThre = ABS(ACITable[0].m_nRed,nRed) + 
				ABS(ACITable[0].m_nGreen,nGreen) + 
				ABS(ACITable[0].m_nBlue,nBlue);
	*pACI = 1;

	for (int i=1;i<255;i++)
	{
		int nTemp = ABS(ACITable[i].m_nRed,nRed) + 
					ABS(ACITable[i].m_nGreen,nGreen) + 
					ABS(ACITable[i].m_nBlue,nBlue);

		if (nTemp < nThre)
		{
			nThre = nTemp;
			*pACI = i + 1;
		}
	}

	return true;
}

